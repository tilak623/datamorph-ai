import { Octokit } from '@octokit/rest';
import { GeneratedFile } from './codeGenerator';

export interface PublishResult {
  success: boolean;
  repoUrl?: string;
  repoName?: string;
  error?: string;
}

export async function pushProjectToGithub(
  accessToken: string,
  repoName: string,
  isPrivate: boolean,
  description: string,
  files: GeneratedFile[]
): Promise<PublishResult> {
  try {
    const octokit = new Octokit({ auth: accessToken });

    // 1. Get authenticated user
    const { data: user } = await octokit.rest.users.getAuthenticated();

    // 2. Check if repo already exists
    try {
      const existing = await octokit.rest.repos.get({
        owner: user.login,
        repo: repoName,
      });
      if (existing.data) {
        return {
          success: false,
          error: `Repository '${repoName}' already exists in your GitHub account. Please choose a different name.`,
        };
      }
    } catch (err: any) {
      // 404 means repo does not exist, which is what we want!
      if (err.status !== 404) {
        // another error
      }
    }

    // 3. Create repository with auto_init: true so a default commit exists
    const { data: repo } = await octokit.rest.repos.createForAuthenticatedUser({
      name: repoName,
      description: description || 'Interactive scrollytelling data story generated by DataMorph AI',
      private: isPrivate,
      auto_init: true,
    });

    const owner = user.login;
    const repoSlug = repo.name;
    const branch = repo.default_branch || 'main';

    // Wait a brief moment for GitHub to initialize branch
    await new Promise((resolve) => setTimeout(resolve, 1500));

    // 4. Get the latest commit SHA of the default branch
    const { data: refData } = await octokit.rest.git.getRef({
      owner,
      repo: repoSlug,
      ref: `heads/${branch}`,
    });
    const latestCommitSha = refData.object.sha;

    // 5. Create Blobs for each file
    const treeItems: { path: string; mode: '100644'; type: 'blob'; sha: string }[] = [];

    for (const file of files) {
      const { data: blobData } = await octokit.rest.git.createBlob({
        owner,
        repo: repoSlug,
        content: Buffer.from(file.content).toString('base64'),
        encoding: 'base64',
      });

      treeItems.push({
        path: file.path,
        mode: '100644',
        type: 'blob',
        sha: blobData.sha,
      });
    }

    // 6. Create Git Tree
    const { data: newTree } = await octokit.rest.git.createTree({
      owner,
      repo: repoSlug,
      base_tree: latestCommitSha,
      tree: treeItems,
    });

    // 7. Create Git Commit
    const { data: newCommit } = await octokit.rest.git.createCommit({
      owner,
      repo: repoSlug,
      message: 'feat: initial editorial scrollytelling release generated by DataMorph AI',
      tree: newTree.sha,
      parents: [latestCommitSha],
    });

    // 8. Update Git Ref to point to new commit
    await octokit.rest.git.updateRef({
      owner,
      repo: repoSlug,
      ref: `heads/${branch}`,
      sha: newCommit.sha,
    });

    return {
      success: true,
      repoUrl: repo.html_url,
      repoName: repo.full_name,
    };
  } catch (err: any) {
    console.error('GitHub Push failed:', err);
    return {
      success: false,
      error: err.message || 'An unexpected error occurred while pushing to GitHub.',
    };
  }
}
